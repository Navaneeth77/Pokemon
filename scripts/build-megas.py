#!/usr/bin/env python3
"""Writes src/data/more-megas.js: the Mega Evolutions added from PMD SpriteCollab sheets (scripts/fetch-megas.py).

Official base and Mega stats, types and abilities come from PokeAPI's CSV tables (docs/POKEAPI-LICENSE.md) in
<cache>. A Mega whose ability this game doesn't have yet keeps its base form's ability.

Usage: scripts/build-megas.py <cache dir> <game.json>
  game.json: {"species": {base: {ability, name}}, "abilities": [...], "colors": TYPE_COLORS} dumped from the game.
"""
import csv, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE, GAME = sys.argv[1], json.load(open(sys.argv[2]))
rows = lambda name: list(csv.DictReader(open(os.path.join(CACHE, name), encoding='utf-8')))
camel = lambda s: s.split('-')[0] + ''.join(w[:1].upper() + w[1:] for w in s.split('-')[1:])
STAT = {'1': 'hp', '2': 'atk', '3': 'def', '4': 'spa', '5': 'spd', '6': 'spe'}
poke = {r['identifier']: r for r in rows('pokemon.csv')}
stats, types, abil = {}, {}, {}
for r in rows('pokemon_stats.csv'):
    stats.setdefault(r['pokemon_id'], {})[STAT[r['stat_id']]] = int(r['base_stat'])
tname = {r['id']: r['identifier'] for r in rows('types.csv')}
for r in rows('pokemon_types.csv'):
    types.setdefault(r['pokemon_id'], []).append((int(r['slot']), tname[r['type_id']]))
aname = {r['id']: r['identifier'] for r in rows('abilities.csv')}
english = {r['ability_id']: r['name'] for r in rows('ability_names.csv') if r['local_language_id'] == '9'}
for r in rows('pokemon_abilities.csv'):
    if r['is_hidden'] == '0':
        abil.setdefault(r['pokemon_id'], []).append((int(r['slot']), r['ability_id']))
FORM = {'tatsugiri': 'tatsugiri-curly-mega'}
BASE = {'tatsugiri': 'tatsugiri-curly', 'zygarde': 'zygarde-50'}

megas, verified, kept = [], {}, []
for base, g in GAME['species'].items():
    if g.get('mega'):
        continue
    form, b = poke[FORM.get(base, f'{base}-mega')], poke[BASE.get(base, base)]
    t = [x for _, x in sorted(types[form['id']])]
    a = sorted(abil.get(form['id'], []))
    ab_id = camel(aname[a[0][1]]) if a else None
    if ab_id not in GAME['abilities']:
        kept.append(f"{base} ({english.get(a[0][1], 'none listed') if a else 'none listed'})")
        ab_id, ab_name = g['ability'], None
    else:
        ab_name = english[a[0][1]]
    c1, c2 = GAME['colors'][t[0]][0], GAME['colors'][t[-1]][1]
    mid = f'{base}Mega'
    megas.append([base, mid, f"Mega {g['name']}", {'sprite': f'{base}-mega', 'ability': ab_id, 'aura': ['#ffffff', c1, c2]}])
    verified[mid] = {'base': stats[b['id']], 'form': stats[form['id']], 'ability': ab_name or g['ability'], 'types': t}

with open(os.path.join(ROOT, 'src/data/more-megas.js'), 'w', encoding='utf-8') as f:
    f.write('// Generated by scripts/build-megas.py from PokeAPI (docs/POKEAPI-LICENSE.md). Do not edit by hand.\n')
    f.write('// Mega Evolutions with complete PMD SpriteCollab sheets (scripts/fetch-megas.py): [base, id, name, overrides],\n')
    f.write('// and their official base/Mega stats and types (species.js scales the base form\'s tuned stats by them).\n')
    f.write('export const MORE_MEGAS = [\n' + ''.join(f'  {json.dumps(m, separators=(",", ":"))},\n' for m in megas) + '];\n\n')
    f.write('export const MORE_MEGA_STATS = ' + json.dumps(verified, indent=1) + ';\n')
print(f'{len(megas)} Megas written' + (f'; kept the base ability for {", ".join(kept)}' if kept else ''))
